/** Land mask and shore-distance (chamfer, capped at 9) for chunk (cx,cy) incl. an AP-tile apron. */
export function landMask(cx: number, cy: number): LandMask {
  const S = CH + 2 * AP,
    ox = cx * CH - AP,
    oy = cy * CH - AP;
  const E: number[] = [];
  for (let e = 0; e < EDGES.length; e += 4) {
    const ya = EDGES[e + 1],
      yb = EDGES[e + 3];
    if (Math.max(ya, yb) < oy || Math.min(ya, yb) > oy + S || Math.max(EDGES[e], EDGES[e + 2]) <= ox)
      continue;
    E.push(EDGES[e], ya, EDGES[e + 2], yb);
  }
  const mask = new Uint8Array(S * S),
    dist = new Uint8Array(S * S);
  for (let j = 0; j < S; j++)
    for (let i = 0; i < S; i++) {
      const m = crossings(E, ox + i + 0.5, oy + j + 0.5) ? 1 : 0;
      mask[j * S + i] = m;
      dist[j * S + i] = m ? 9 : 0;
    }
  const at = (r: number, c: number) => (r < 0 || c < 0 || r >= S || c >= S ? 9 : dist[r * S + c]);
  for (let r = 0; r < S; r++)
    for (let c = 0; c < S; c++) {
      const i = r * S + c;
      if (dist[i])
        dist[i] = Math.min(
          dist[i],
          at(r - 1, c - 1) + 1,
          at(r - 1, c) + 1,
          at(r - 1, c + 1) + 1,
          at(r, c - 1) + 1,
        );
    }
  for (let r = S - 1; r >= 0; r--)
    for (let c = S - 1; c >= 0; c--) {
      const i = r * S + c;
      if (dist[i])
        dist[i] = Math.min(
          dist[i],
          at(r + 1, c + 1) + 1,
          at(r + 1, c) + 1,
          at(r + 1, c - 1) + 1,
          at(r, c + 1) + 1,
        );
    }
  let land = 0;
  for (let j = AP; j < AP + CH; j++) for (let i = AP; i < AP + CH; i++) land += mask[j * S + i];
  return { S, mask, dist, landFrac: land / (CH * CH) };
}
